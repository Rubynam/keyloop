#!/usr/bin/env python3
"""Builds loadtest/data/seed-refs.json from seeding/sql/*.sql (Spec06 §5.4).

The input and expected files refer to seed rows by name ({{ref.dealerships.Q7}}) instead of raw ids,
so this file is the only place that knows the UUIDs. Re-run it after seeding/generate.py:

    python3 loadtest/tools/build_seed_refs.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SQL = ROOT / "seeding" / "sql"
OUT = ROOT / "loadtest" / "data" / "seed-refs.json"


def rows(table):
    txt = next(p for p in SQL.glob("*.sql") if re.fullmatch(rf"\d\d_{table}\.sql", p.name)).read_text()
    cols = re.search(r"INSERT INTO \w+ \(([^)]*)\)", txt).group(1).split(", ")
    out = []
    for line in txt.splitlines():
        line = line.strip()
        if not line.startswith("("):
            continue
        body = line.split("--", 1)[0].rstrip().rstrip(",;").strip()[1:-1]
        vals = [a if a or not b else b for a, b in re.findall(r"'((?:[^']|'')*)'|(NULL|TRUE|FALSE|-?\d+)", body)]
        out.append(dict(zip(cols, vals)))
    return out


def by(table, key, value):
    return next(r for r in rows(table) if r[key] == value)["id"]


vt = {r["id"]: r["code"] for r in rows("vehicle_types")}
vehicles = rows("vehicles")


def vehicle(vin):
    v = next(v for v in vehicles if v["vin"] == vin)
    return {"vehicleId": v["id"], "customerId": v["customer_id"], "vin": vin, "vehicleType": vt[v["vehicle_type_id"]]}


dealer = lambda name: by("dealerships", "name", name)  # noqa: E731
service = lambda code: by("service_types", "code", code)  # noqa: E731

refs = {
    "_source": "generated by loadtest/tools/build_seed_refs.py from seeding/sql — do not edit by hand",
    "dealerships": {
        "Q7": dealer("Keyloop Service Quận 7"),                    # main hub, every bay kind
        "LONDON": dealer("Keyloop London Park Royal"),             # 1 oil-change technician → capacity 1
        "OSLO_EV": dealer("Keyloop EV Centre Oslo"),               # high-voltage bays only
        "ROTTERDAM_TRUCK": dealer("Keyloop Truck Depot Rotterdam"),
        "KATHMANDU": dealer("Keyloop Kathmandu"),                  # UTC+05:45
        "KIRITIMATI": dealer("Keyloop Kiritimati"),                # UTC+14
        "EXPRESS_KIOSK": dealer("Keyloop Express Kiosk"),          # open 60 min only
        "STAFF_ONLY": dealer("Keyloop Staff Only Workshop"),       # technicians, no bays
        "CLOSED": dealer("Keyloop Closed for Renovation"),         # everything inactive
    },
    "serviceTypes": {c: service(c) for c in (
        "OIL_CHANGE", "TYRE_ROTATION", "MAJOR_SERVICE", "DIAGNOSTICS", "BRAKE_SERVICE",
        "EV_BATTERY_CHECK", "TRUCK_AXLE_SERVICE", "WHEEL_ALIGNMENT", "DASHBOARD_LIGHT_RESET",
        "HYDROGEN_FUEL_CELL_SERVICE")},
    "vehicleTypes": {code: i for i, code in vt.items()},
    "vehicles": {
        "HYBRID": vehicle("2Z3F19S3L37K2KLG8"),
        "ELECTRIC_TRUCK": vehicle("18EP82JXHUE4H5TG0"),
        "HYDROGEN": vehicle("FC9SGGDXMESMS62T0"),
        "CLASSIC_1965": vehicle("A7HL9WSB3DHYJT7DZ"),
    },
    "customers": {
        "NO_VEHICLE": next(c["id"] for c in rows("customers") if c["id"] not in {v["customer_id"] for v in vehicles}),
    },
    # Cars that a standard bay takes: random picks for booking load and the race
    "pools": {
        "standardCars": [vehicle(v["vin"]) for v in vehicles
                         if vt[v["vehicle_type_id"]] in ("GASOLINE_CAR", "DIESEL_CAR", "HYBRID_CAR")],
    },
}

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(json.dumps(refs, indent=2, ensure_ascii=False) + "\n")
print(f"wrote {OUT.relative_to(ROOT)}: {len(refs['pools']['standardCars'])} standard cars")
